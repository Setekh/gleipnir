/// The (keystroke, action name) table for a platform.
pub fn keymap(macos: bool) -> impl Iterator<Item = (&'static str, &'static str)> {
    let platform = if macos { MACOS } else { LINUX };
    COMMON.iter().chain(platform).copied()
}

fn binding(keys: &'static str, action: &str) -> KeyBinding {
    let context = Some("Editor");
    macro_rules! actions_by_name {
        ($($name:ident),* $(,)?) => {
            match action {
                $(stringify!($name) => KeyBinding::new(keys, $name, context),)*
                other => panic!("unknown editor action {other}"),
            }
        };
    }
    actions_by_name!(
        MoveLeft,
        MoveRight,
        MoveUp,
        MoveDown,
        MoveWordLeft,
        MoveWordRight,
        MoveLineStart,
        MoveLineEnd,
        MoveDocStart,
        MoveDocEnd,
        PageUp,
        PageDown,
        SelectLeft,
        SelectRight,
        SelectUp,
        SelectDown,
        SelectWordLeft,
        SelectWordRight,
        SelectLineStart,
        SelectLineEnd,
        SelectDocStart,
        SelectDocEnd,
        SelectPageUp,
        SelectPageDown,
        SelectAll,
        ExtendSelection,
        ShrinkSelection,
        Backspace,
        Delete,
        DeleteWordLeft,
        DeleteWordRight,
        DeleteLine,
        Newline,
        Indent,
        Outdent,
        DuplicateLine,
        MoveLinesUp,
        MoveLinesDown,
        ToggleComment,
        Undo,
        Redo,
        Copy,
        Cut,
        Paste,
        AddCursorAbove,
        AddCursorBelow,
        AddNextOccurrence,
        RemoveLastOccurrence,
        SelectAllOccurrences,
        CollapseSelections,
        Save,
    )
}

pub fn bind_keys(cx: &mut App) {
    let bindings: Vec<KeyBinding> = keymap(cfg!(target_os = "macos"))
        .map(|(keys, action)| binding(keys, action))
        .collect();
    cx.bind_keys(bindings);
    crate::semantics::popup_bindings(cx);
    crate::caret_gesture::bind_keys(cx);
}
